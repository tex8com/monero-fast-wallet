export function hasDuplicatedAdjacentWord(value: string): boolean {
  const normalized = value.replace(/\{[A-Za-z0-9_]+\}/g, ' ');
  const words = [...normalized.matchAll(/\p{L}{2,}/gu)];
  return words.some((match, index) => {
    if (index === 0) return false;
    const previous = words[index - 1];
    const previousEnd = (previous.index ?? 0) + previous[0].length;
    const gap = normalized.slice(previousEnd, match.index);
    return /^\s+$/u.test(gap)
      && match[0].localeCompare(previous[0], undefined, { sensitivity: 'base' }) === 0;
  });
}

export function isGeneratedTranslationCriticallyUnsafe(source: string, translated: string): boolean {
  const sourceLength = [...source].length;
  const translatedLength = [...translated].length;
  const shortUiText = sourceLength <= 20 && !/[.!?]\s*$/.test(source);
  return (shortUiText && translatedLength > Math.max(18, sourceLength * 3))
    || (sourceLength > 20 && translatedLength > sourceLength * 2.2 && translatedLength - sourceLength > 20)
    || /<\s*\/?\s*x?\d*\s*\/?>|&(?:quot|amp|lt|gt);/iu.test(translated)
    || hasDuplicatedAdjacentWord(translated)
    || (!/\d/.test(source) && /\d/.test(translated));
}

export function isGeneratedTranslationSafe(source: string, translated: string): boolean {
  if (isGeneratedTranslationCriticallyUnsafe(source, translated)) return false;
  const sourceLength = [...source].length;
  const translatedLength = [...translated].length;
  if (translatedLength > sourceLength * 1.8 && translatedLength - sourceLength > 8) return false;
  return true;
}

export function applyManualTranslationOverrides<T extends Record<string, string>>(
  locale: string,
  english: T,
  translated: T,
): T {
  const overrides = manualTranslationOverrides[locale as ManualTranslationLocale];
  return Object.fromEntries(
    Object.entries(english).map(([key, source]) => {
      const reviewed = overrides?.[source];
      if (reviewed) return [key, reviewed];
      const generated = translated[key];
      return [key, isGeneratedTranslationSafe(source, generated) ? generated : source];
    }),
  ) as T;
}
